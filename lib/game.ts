export function upgradeWaitingLibrary(room:any){
 if(room.status!=='waiting'||room.catalogVersion>=2)return false;
 const countries=new Set(room.library.map((q:any)=>normalize(q.country)));
 const ids=new Set(room.library.map((q:any)=>q.id));
 for(const q of bank.filter(q=>q.id.startsWith('world-'))){
  if(countries.has(normalize(q.country)))continue;
  let id=q.id;while(ids.has(id))id+='-catalog';
  room.library.push({...q,id,choices:[...q.choices]});ids.add(id);countries.add(normalize(q.country));
 }
 room.catalogVersion=2;return true;
}
